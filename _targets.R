# Regimes for four-waves LTMLE analyses
regimes <- list(
  "0-0-0-0" = c(0, 0, 0, 0),
  "0-0-1-0" = c(0, 0, 1, 0),
  "0-1-0-0" = c(0, 1, 0, 0),
