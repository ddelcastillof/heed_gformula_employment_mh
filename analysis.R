age_correctors <- data |> 
  filter(!is.na(age_dv)) |> 
  summarise(base_age = mean(age_dv - t0) |> round(), .by = pidp)

expanded_data <- data |>
  filter(!is.na(age_dv)) |> 
  select(pidp) |> 
  unique() |> 
  slice_sample(n = 2000) |> 
  expand_grid(tibble(t0 = 0:4)) |> 
  unique() |> 
  left_join(data)

expanded_data <- expanded_data |> 
  inner_join(age_correctors, by = "pidp") |> 
  mutate(age_dv = base_age)


