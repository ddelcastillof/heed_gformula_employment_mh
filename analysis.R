data <-
  data |>
  filter(wave >= 6) |> 
  mutate(
    across(c(pidp, ppid, hidp, wave, pns1pid, pns2pid),
           as.integer),
    across(where(haven::is.labelled),
           haven::zap_labels),
    wnw_race = case_when(racel_dv %in% 1:4 ~ 0, racel_dv %in% 5:97 ~  1, .default = NA),
